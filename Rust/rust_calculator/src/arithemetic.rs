pub fn add_values(x: i32, y: i32) -> i32 {
    // implicit return (no semicolon)
    x + y
}

pub fn multiply_values(x: i32, y:i32) -> i32 {
    x * y
}

pub fn subtract_values(x: i32, y: i32) -> i32 {
    // implicit return (no semicolon)
    x - y
}

pub fn divide_values(x: i32, y:i32) -> i32 {
    x / y
}